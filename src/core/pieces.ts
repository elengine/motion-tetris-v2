/**
 * テトロミノ定義 — SRS 標準準拠。
 * cells[r] = 4x4 (I以外は 3x3) ボックス内の [x, y] 座標。y は下向き正。
 * 回転はこの 3x3/4x4 ボックス内で 90° 回転した形状を明示的に列挙する
 * （実行時の回転計算をしない → 表示と論理のズレが構造的に起きない）。
 */
export type PieceType = 'I' | 'O' | 'T' | 'S' | 'Z' | 'J' | 'L';

export interface PieceDef {
  type: PieceType;
  color: string;
  glow: string;
  /** 4回転状態のセル。ボックスサイズは size フィールド参照 */
  size: number;
  cells: [number, number][][];
}

const T = (
  type: PieceType,
  color: string,
  glow: string,
  size: number,
  cells: [number, number][][],
): PieceDef => ({ type, color, glow, size, cells });

